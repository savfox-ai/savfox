pub async fn run_doctor(cmd: DoctorCommand) -> anyhow::Result<()> {
    println!("{}", "Savfox Doctor".bold().underline());
    println!("Running diagnostic checks...");

    let savfox_home = match cmd.savfox_home {
        Some(p) => p,
        None => find_savfox_home().unwrap_or_else(|_| {
            dirs::home_dir()
                .unwrap_or_else(|| PathBuf::from("."))
                .join(".savfox")
        }),
    };

    let mut summary = DoctorSummary::default();

    check_build_info(&mut summary);
    check_config_integrity(&savfox_home, cmd.yes, &mut summary);
    check_dependencies(&mut summary);
    check_environment_setup(&savfox_home, &mut summary);
    check_state_dirs(&savfox_home, cmd.yes, &mut summary);
    check_web_ui_assets(&savfox_home, &mut summary);
    check_auth_profiles(&savfox_home, cmd.yes, &mut summary);

    if cmd.network {
        check_network(&mut summary).await;
    }

    check_disk_space(&savfox_home, &mut summary);
    check_sessions(&savfox_home, &mut summary);
    check_gateway(&mut summary).await;

    println!();
    println!("{}", "Summary".bold());
    println!("{}", "-------".bold());
    println!(
        "  {} OK  {} WARN  {} FAIL",
        summary.ok.to_string().green(),
        summary.warn.to_string().yellow(),
        summary.fail.to_string().red()
    );

    if !summary.repaired.is_empty() {
        println!();
        println!("{}", "Auto-repair actions".bold());
        println!("{}", "-------------------".bold());
        for item in &summary.repaired {
            println!("  - {item}");
        }
    }

    if !summary.suggestions.is_empty() {
        println!();
        println!("{}", "Suggested fixes".bold());
        println!("{}", "---------------".bold());
        for suggestion in &summary.suggestions {
            println!("  - {suggestion}");
        }
    }

    println!();
    println!("{}", "Done.".bold());
    Ok(())
}
