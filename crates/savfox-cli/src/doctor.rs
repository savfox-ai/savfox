/// Diagnose system health and configuration.
#[derive(Debug, Parser)]
pub struct DoctorCommand {
    /// Check network connectivity to LLM providers.
    #[clap(long, default_value_t = true)]
    pub network: bool,

    /// Savfox home directory override.
    #[clap(long)]
    pub savfox_home: Option<PathBuf>,

    /// Auto-repair common issues when possible.
    #[clap(long)]
    pub yes: bool,
}

#[derive(Default)]
struct DoctorSummary {
    ok: u32,
    warn: u32,
    fail: u32,
    suggestions: Vec<String>,
    repaired: Vec<String>,
}

impl DoctorSummary {
    fn ok(&mut self, label: &str, detail: &str) {
        println!("  {} {}: {}", "[OK]".green(), label, detail);
        self.ok = self.ok.saturating_add(1);
    }

    fn warn(&mut self, label: &str, detail: &str) {
        println!("  {} {}: {}", "[WARN]".yellow(), label, detail);
        self.warn = self.warn.saturating_add(1);
    }

    fn fail(&mut self, label: &str, detail: &str) {
        println!("  {} {}: {}", "[FAIL]".red(), label, detail);
        self.fail = self.fail.saturating_add(1);
    }

    fn suggest(&mut self, command: impl Into<String>) {
        let command = command.into();
        if !self.suggestions.iter().any(|s| s == &command) {
            self.suggestions.push(command);
        }
    }

    fn repaired(&mut self, item: impl Into<String>) {
        self.repaired.push(item.into());
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct StoredAuthProfile {
    id: String,
    api_key: String,
    #[serde(default)]
    usage_tokens: u64,
    #[serde(default)]
    usage_cost_usd: f64,
    #[serde(default)]
    cooldown_until: Option<u64>,
    #[serde(default)]
    last_error: Option<String>,
}

