fn check_config_integrity(savfox_home: &Path, auto_repair: bool, summary: &mut DoctorSummary) {
    println!();
    println!("{}", "Configuration".bold());
    println!("{}", "-------------".bold());

    let config_path = savfox_home.join(CONFIG_TOML_FILE);
    if !config_path.exists() {
        summary.warn(
            "Config file",
            &format!("{} (not found)", config_path.display()),
        );
        summary.suggest("savfox wizard");
        if auto_repair {
            if let Err(err) = std::fs::write(
                &config_path,
                "# Generated by `savfox doctor --yes`\n# Fill in provider and channel settings.\n",
            ) {
                summary.fail(
                    "Auto-repair",
                    &format!("failed to create config.toml: {err}"),
                );
            } else {
                summary.repaired(format!("created {}", config_path.display()));
                summary.ok("Auto-repair", &format!("created {}", config_path.display()));
            }
        }
        return;
    }

    let contents = match std::fs::read_to_string(&config_path) {
        Ok(c) => c,
        Err(e) => {
            summary.fail(
                "Config file",
                &format!("{} (read error: {})", config_path.display(), e),
            );
            summary.suggest("savfox config validate");
            return;
        }
    };

    let toml_value = match contents.parse::<toml::Value>() {
        Ok(value) => {
            summary.ok(
                "Config parse",
                &format!("{} (valid TOML)", config_path.display()),
            );
            value
        }
        Err(e) => {
            summary.fail(
                "Config parse",
                &format!("{} (parse error: {})", config_path.display(), e),
            );
            summary.suggest("savfox config validate");
            return;
        }
    };

    let json_value = match serde_json::to_value(toml_value) {
        Ok(value) => value,
        Err(e) => {
            summary.fail(
                "Config schema",
                &format!("TOML to JSON conversion failed: {e}"),
            );
            summary.suggest("savfox config validate");
            return;
        }
    };

    let validation = validate_config(&json_value);
    let error_count = validation
        .errors
        .iter()
        .filter(|e| matches!(e.severity, Severity::Error))
        .count();
    let warning_count = validation
        .errors
        .iter()
        .filter(|e| matches!(e.severity, Severity::Warning))
        .count();

    if error_count == 0 && warning_count == 0 {
        summary.ok("Config schema", "no validation issues");
    } else {
        if error_count > 0 {
            summary.fail(
                "Config schema",
                &format!("{error_count} error(s), {warning_count} warning(s)"),
            );
            summary.suggest("savfox config validate");
        } else {
            summary.warn(
                "Config schema",
                &format!("{warning_count} warning(s), no hard errors"),
            );
        }

        for issue in validation.errors.iter().take(8) {
            match issue.severity {
                Severity::Error => {
                    summary.fail("  schema", &format!("{}: {}", issue.field, issue.message))
                }
                Severity::Warning => {
                    summary.warn("  schema", &format!("{}: {}", issue.field, issue.message))
                }
            }
        }
    }

    summary.ok("Savfox home", &format!("{}", savfox_home.display()));
}

/// Describes a binary to look for on the PATH.
struct BinCheck {
    label: &'static str,
    candidates: &'static [&'static str],
    required: bool,
    purpose: &'static str,
}

fn check_dependencies(summary: &mut DoctorSummary) {
    println!();
    println!("{}", "Dependencies".bold());
    println!("{}", "------------".bold());

    let bins = [
        BinCheck {
            label: "git",
            candidates: &["git"],
            required: true,
            purpose: "version control",
        },
        BinCheck {
            label: "node",
            candidates: &["node"],
            required: false,
            purpose: "MCP servers",
        },
        BinCheck {
            label: "docker",
            candidates: &["docker"],
            required: false,
            purpose: "sandbox containers",
        },
        BinCheck {
            label: "ffmpeg",
            candidates: &["ffmpeg"],
            required: false,
            purpose: "media/audio processing",
        },
        BinCheck {
            label: "signal-cli",
            candidates: &["signal-cli"],
            required: false,
            purpose: "Signal channel",
        },
        BinCheck {
            label: "chrome",
            candidates: &["google-chrome", "chromium", "chrome", "msedge"],
            required: false,
            purpose: "browser automation",
        },
    ];

    for bin in &bins {
        let mut found_path = None;
        for candidate in bin.candidates {
            if let Ok(path) = which::which(candidate) {
                found_path = Some(path);
                break;
            }
        }

        match found_path {
            Some(path) => summary.ok(bin.label, &format!("{} ({})", path.display(), bin.purpose)),
            None if bin.required => {
                summary.fail(bin.label, &format!("not found on PATH ({})", bin.purpose));
                summary.suggest(format!("Install {}", bin.label));
            }
            None => summary.warn(
                bin.label,
                &format!("not found on PATH (optional, for {})", bin.purpose),
            ),
        }
    }
}

fn check_environment_setup(savfox_home: &Path, summary: &mut DoctorSummary) {
    println!();
    println!("{}", "Environment".bold());
    println!("{}", "-----------".bold());

    let path_var = std::env::var_os("PATH");
    let path_has_home = path_var
        .as_deref()
        .is_some_and(|v| path_contains(v, savfox_home));
    if path_has_home {
        summary.ok("PATH", "contains savfox home path");
    } else {
        summary.warn("PATH", "does not contain savfox home path");
        summary.suggest("Add Savfox install path to PATH");
    }

    let completion_paths = completion_paths();
    let installed: Vec<PathBuf> = completion_paths
        .into_iter()
        .filter(|path| path.exists())
        .collect();
    if installed.is_empty() {
        summary.warn("Completions", "no shell completion file detected");
        summary.suggest("savfox completion <bash|zsh|fish|powershell> > <completion-file>");
    } else {
        let list = installed
            .iter()
            .map(|p| p.display().to_string())
            .collect::<Vec<_>>()
            .join(", ");
        summary.ok("Completions", &list);
    }
}

fn check_state_dirs(savfox_home: &Path, auto_repair: bool, summary: &mut DoctorSummary) {
    println!();
    println!("{}", "State Directory".bold());
    println!("{}", "---------------".bold());

    let required_dirs = [
        savfox_home.to_path_buf(),
        savfox_home.join("sessions"),
        savfox_home.join("gateway"),
        savfox_home.join("logs"),
        savfox_home.join("auth"),
    ];

    for dir in required_dirs {
        if dir.exists() {
            summary.ok("Dir", &format!("{} (exists)", dir.display()));
        } else if auto_repair {
            match std::fs::create_dir_all(&dir) {
                Ok(()) => {
                    summary.ok("Dir", &format!("{} (created)", dir.display()));
                    summary.repaired(format!("created directory {}", dir.display()));
                }
                Err(err) => {
                    summary.fail("Dir", &format!("{} (create failed: {err})", dir.display()));
                    summary.suggest(format!("Create directory {}", dir.display()));
                }
            }
        } else {
            summary.warn("Dir", &format!("{} (missing)", dir.display()));
            summary.suggest(format!("mkdir -p {}", dir.display()));
        }
    }

    let write_test_path = savfox_home.join(".doctor_write_test");
    match std::fs::write(&write_test_path, b"ok") {
        Ok(()) => {
            let _ = std::fs::remove_file(&write_test_path);
            summary.ok("Permissions", "state directory is writable");
        }
        Err(err) => {
            summary.fail(
                "Permissions",
                &format!("cannot write in savfox home: {err}"),
            );
            summary.suggest("Fix file permissions for Savfox state directory");
        }
    }
}

